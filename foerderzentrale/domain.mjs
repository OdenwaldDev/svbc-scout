const hasText = value => typeof value === "string" && Boolean(value.trim());
export function isOriginal(source, day) {
  return source?.kind === "primary" && sourceUrl(source.url) && isDay(source.checked) &&
    source.checked <= day && hasText(source.title) && hasText(source.section) && hasText(source.excerpt);
}
export function upcomingDates(items, day = today()) {
  const limit=new Date(Date.parse(day)+30*86400000).toISOString().slice(0,10);
  const inRange=value=>isDay(value) && day<=value && value<=limit;
  return items.flatMap(item=>{
    const activeOffers=new Set(item.costs.map(row=>row.offer));
    const dates=item.sources.filter(s=>s.kind==="quote" && activeOffers.has(s.id) && inRange(s.validUntil))
      .map(s=>({date:s.validUntil,caseId:item.id,title:item.title,reason:"Angebot gültig bis"}));
    const p=item.program;
    if (p.status==="open" && inRange(p.until) && item.sources.some(s=>s.id===p.source && isOriginal(s,day))) {
      dates.push({date:p.until,caseId:item.id,title:item.title,reason:"Belegte Antragsfrist"});
    }
    return dates;
  }).sort((a,b)=>a.date.localeCompare(b.date)).slice(0,12);
}
export function caseDecisionText(item, facts, day = today()) {
  const report = evaluate(item, facts, day);
  const lines = ["Interne Entscheidungsvorlage", item.title, "Stand " + day.split("-").reverse().join("."), "",
    item.need, item.measure, "",
    "Geprüftes Programm: " + (item.program.title || "Offen"),
    "Ergebnis: " + states[report.status]];
  if (item.followUp) lines.push("", "Nächster Schritt", item.followUp);
  if (item.intake === "suggested") lines.push("", "Recherchevorschlag. Bedarf und Maßnahme im Verein bestätigen.");
  if (item.program.route) lines.push("", "Einreichungsweg", item.program.route);
  const application = item.sources.find(source => source.id === item.applicationSource && isOriginal(source, day));
  if (application) lines.push(application.title, application.url);
  lines.push("", "Finanzierung", "Gesamtkosten " + euro(report.total), "Mögliche Förderung " + euro(report.funding), "Eigenanteil " + euro(report.own));
  if (item.offerVariants?.length) {
    lines.push("", "Angebotsvergleich");
    for (const variant of item.offerVariants) {
      lines.push(variant.title + ": " + euro(variant.net) + " netto, " + euro(variant.gross) + " brutto");
    }
  }
  if (item.offerRequests?.length) {
    lines.push("", "Angebotsanfragen");
    for (const request of item.offerRequests) {
      lines.push([request.supplier, offerRequestStatuses[request.status], request.date].filter(Boolean).join(" · "), request.note);
    }
  }
  for (const route of item.fundingRoutes || []) {
    lines.push("", route.title, routeStatuses[route.status], route.finding, route.next);
    if (route.question) lines.push("", "Frage für eine Voranfrage", route.question);
    for (const id of [route.source, route.portal]) {
      const source = item.sources.find(row => row.id === id);
      if (source && isOriginal(source, day)) lines.push(source.title + " · " + source.section, source.url);
    }
  }
  const open = report.checks.filter(check => check.status === "unknown");
  if (open.length) lines.push("", "Offene Prüfpunkte", ...open.map(check => "- " + check.name + ": " + check.reason));
  return lines.join("\r\n") + "\r\n";
}
